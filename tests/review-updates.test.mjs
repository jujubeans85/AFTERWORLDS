import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { prepareLocalUpdateReview } from '../scripts/review-updates.mjs';
import { loadResearchWorld } from '../src/research-data.js';
import { AcceptedUpdateMonitor, loadAcceptedHistory } from '../src/accepted-updates.js';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
test('synthetic update fixture is isolated and real monitor/loaders verify offers, history and corrupt bytes', async t => {
  const acceptedPath = path.join(root, 'dist/assets/research/accepted-manifest.json');
  const before = await fs.readFile(acceptedPath);
  const activationPath = path.join(root, 'data-updates/design-activation');
  const approvalBefore = await fs.readdir(activationPath).catch(error => { if (error.code === 'ENOENT') return []; throw error; });
  const { directory, record } = await prepareLocalUpdateReview();
  t.after(() => fs.rm(directory, { recursive: true, force: true }));
  assert.deepEqual(await fs.readFile(acceptedPath), before);
  assert.deepEqual(await fs.readdir(activationPath).catch(error => { if (error.code === 'ENOENT') return []; throw error; }), approvalBefore);
  await assert.rejects(fs.access(path.join(directory, 'assets/research/accepted-manifest.json')));
  assert.equal(record.authorizesRuntimeActivation, false);
  let stage = 'baseline';
  const fetchImpl = async url => new Response(await fs.readFile(path.join(directory, url === '/assets/research/accepted-manifest.json' ? `fixtures/manifest-${stage}.json` : url)), { status: 200 });
  const monitor = new AcceptedUpdateMonitor({ fetchImpl }); t.after(() => monitor.dispose());
  const baselineManifest = (await monitor.check()).manifest;
  let current = await loadResearchWorld(baselineManifest.worlds['430'], { fetchImpl });
  const baseline = current;
  stage = 'update';
  const updateManifest = (await monitor.check()).manifest;
  assert.equal(current.revision, record.baselineRevision, 'checking alone cannot apply a revision');
  const changed = await loadResearchWorld(updateManifest.worlds['430'], { fetchImpl });
  assert.equal(changed.rows[0].value, baseline.rows[0].value + 1);
  assert.deepEqual(changed.rows.slice(1), baseline.rows.slice(1));
  assert.equal(changed.revision, record.syntheticRevision);
  current = changed;
  stage = 'corrupt';
  await assert.rejects(loadResearchWorld((await monitor.check()).manifest.worlds['430'], { fetchImpl }), /integrity|digest/i);
  assert.equal(current.revision, record.syntheticRevision);
  const versions = await loadAcceptedHistory(updateManifest.history['430'], '430', { fetchImpl });
  assert.deepEqual(Object.keys(versions).sort(), [record.baselineRevision, record.syntheticRevision].sort());
  for (const version of Object.values(versions)) assert.equal(version.acceptance.kind, 'local-synthetic-review-fixture');
  current = await loadResearchWorld(versions[record.baselineRevision], { fetchImpl });
  assert.deepEqual(current.rows, baseline.rows);
});
